import assert from 'node:assert/strict'
import { createServer } from 'vite'

const memory = new Map()
globalThis.localStorage = {
  getItem: (key) => memory.get(key) ?? null,
  setItem: (key, value) => memory.set(key, String(value)),
  removeItem: (key) => memory.delete(key),
  key: (index) => [...memory.keys()][index] ?? null,
  get length() { return memory.size },
}
const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' })
try {
  const load = (name) => vite.ssrLoadModule(`/src/utils/${name}.js`)
  const { default: controls } = await vite.ssrLoadModule('/src/data/controls/index.js')
  const { ensureMetObjectiveFinding, ensureNotMetObjectiveFinding } = await load('autoObjectiveFinding')
  const { readObjectiveFinding, writeObjectiveFinding } = await load('objectiveFindings')
  const { writeObjectiveStatus, readObjectiveStatus, getTrendingStatusFromStorage } = await load('objectiveStatus')
  const { writeObjectiveArtifacts } = await load('objectiveArtifacts')
  const { writeObjectiveInterviewedRoles } = await load('objectiveInterviewedRoles')
  const { getDiscrepancyHelper } = await load('discrepancyHelper')
  const { exportProjectState, importProjectState, wipeProjectState } = await load('projectState')
  const control = controls.find((item) => item.id === 'CM.L2-3.4.1')
  const [a, b, c, d] = control.objectives
  const status = (obj, value) => writeObjectiveStatus(control.id, obj.id, value)
  const finding = (obj) => readObjectiveFinding(control.id, obj.id)
  for (const obj of [a, b, d]) status(obj, 'MET')
  writeObjectiveArtifacts(control.id, a.id, ['Baseline record'])
  const met = ensureMetObjectiveFinding(control, a)
  status(a, 'NOT MET')
  const draft = ensureNotMetObjectiveFinding(control, a)
  assert.match(draft.finalText, /C\) Differences: A baseline configuration is not established\./)
  assert.match(draft.finalText, /B\) Implementation as described in the corresponding CM.L2-3.4.1\[a\].*examination of documentation, interviews, and testing/)
  assert.doesNotMatch(draft.finalText, /No noted findings|^D\)|objective is implemented/m)
  assert.equal(draft.previousFinding.finalText, met.finalText)
  assert.equal(getTrendingStatusFromStorage(control), 'NOT MET')
  assert.equal(readObjectiveStatus(control.id, b.id), 'MET')
  assert.equal(readObjectiveStatus(control.id, c.id), 'Unreviewed')
  assert.equal(ensureNotMetObjectiveFinding(control, a), null, 'draft creation is idempotent')
  const helperA = getDiscrepancyHelper(a.text)
  assert.equal(helperA.statement, 'A baseline configuration is not established.')
  const helperB = getDiscrepancyHelper(b.text)
  assert.deepEqual(helperB.components, ['hardware', 'software', 'firmware', 'documentation'])
  const discrepancy = helperB.build(['documentation', 'software'])
  assert.match(discrepancy, /^The baseline configuration did not include software and documentation\./)
  assert.equal(helperB.build([]), '')
  assert.deepEqual(getDiscrepancyHelper(control.objectives[4].text).components, ['hardware', 'software', 'firmware', 'documentation'], 'terminal ; and is not part of a component')
  assert.match(getDiscrepancyHelper('access restrictions are defined;').statement, /are not defined/)
  assert.match(getDiscrepancyHelper('users access approved resources;').statement, /evidence provided did not demonstrate/)
  status(b, 'NOT MET')
  writeObjectiveArtifacts(control.id, b.id, ['Inventory record'])
  const multipartDraft = ensureNotMetObjectiveFinding(control, b)
  assert.match(multipartDraft.finalText, /Discrepancy required/, 'multipart objectives still require component selection')
  const beforeOtherObjective = finding(a)
  ensureNotMetObjectiveFinding(control, b, { differencesText: discrepancy })
  assert.deepEqual(finding(a), beforeOtherObjective, 'saving a discrepancy never changes other objectives')
  assert.match(finding(a).finalText, /CM.L2-3.4.1\[a\]/)
  assert.match(finding(b).finalText, /CM.L2-3.4.1\[b\]/)
  assert.match(finding(b).finalText, /Reviewed Inventory record;/)
  assert.doesNotMatch(finding(b).finalText, /Baseline record/)
  assert.equal(finding(c), null)
  assert.equal(finding(d), null)
  writeObjectiveArtifacts(control.id, b.id, ['Inventory record', 'New evidence'])
  writeObjectiveInterviewedRoles(control.id, b.id, ['System administrator'])
  assert.match(finding(b).finalText, /New evidence;/)
  assert.match(finding(b).finalText, /Interviewed: System administrator/)
  assert.equal(finding(b).differencesText, discrepancy)
  writeObjectiveArtifacts(control.id, b.id, ['New evidence'])
  assert.doesNotMatch(finding(b).finalText, /Reviewed Inventory record/)
  assert.equal(readObjectiveStatus(control.id, b.id), 'NOT MET')
  const beforeRestore = finding(b)
  const backup = JSON.parse(JSON.stringify(exportProjectState(controls)))
  wipeProjectState()
  importProjectState(backup, controls)
  assert.deepEqual(finding(b), beforeRestore, 'draft metadata and discrepancies survive backup/restore')
  status(a, 'MET')
  const backToMet = ensureMetObjectiveFinding(control, a, { replaceNonstandard: true })
  assert.match(backToMet.finalText, /C\) No noted findings or differences\./)
  assert.doesNotMatch(backToMet.finalText, /not fully satisfied|C\) Differences:/)
  assert.equal(backToMet.previousFinding.differencesText, helperA.statement)
  status(a, 'NOT MET')
  ensureNotMetObjectiveFinding(control, a)
  assert.equal(finding(a).differencesText, helperA.statement, 'a new binary negative determination is automatically drafted')
  writeObjectiveFinding(control.id, b.id, { ...finding(b), finalText: `${finding(b).finalText}\nD) Assessor retest history.` })
  ensureNotMetObjectiveFinding(control, b, { differencesText: 'Updated discrepancy.' })
  assert.match(finding(b).finalText, /D\) Assessor retest history\./)
  writeObjectiveFinding(control.id, a.id, { finalText: 'A) Reviewed Record;\nB) Validation is described in the corresponding CM.L2-3.4.1[a] section of the SSP. Old text.\nC) Full implementation of this objective was not confirmed.\nD) Differences: Original discrepancy.\nSecond line.', differencesText: 'Original discrepancy.\nSecond line.' })
  assert.match(finding(a).finalText, /C\) Differences: Original discrepancy\.\nSecond line\.$/)
  assert.doesNotMatch(finding(a).finalText, /Full implementation|D\) Differences/)
  const accessControl = controls.find((item) => item.id === 'AC.L1-3.1.1')
  const deviceObjective = accessControl.objectives.find((item) => item.text.includes('system access is limited to authorized devices'))
  assert.ok(deviceObjective)
  writeObjectiveStatus(accessControl.id, deviceObjective.id, 'NOT MET')
  const deviceDraft = ensureNotMetObjectiveFinding(accessControl, deviceObjective)
  assert.match(deviceDraft.differencesText, /System access is not limited to authorized devices/)
  assert.match(deviceDraft.differencesText, /other systems/)
  ensureNotMetObjectiveFinding(control, a, { differencesText: 'Custom assessor discrepancy.' })
  assert.equal(ensureNotMetObjectiveFinding(control, a), null)
  assert.equal(finding(a).differencesText, 'Custom assessor discrepancy.', 'automatic drafting preserves existing assessor text')
  for (const item of controls) for (const obj of item.objectives) {
    const helper = getDiscrepancyHelper(obj.text)
    assert.ok(helper.statement || helper.components.length)
  }
  console.log('NOT MET findings passed: draft creation, control rollup, independent results, A–C wording, helpers, automatic binary drafts, objective isolation, evidence/role updates, transitions, legacy migration, history, and backup/restore.')
} finally { await vite.close() }
